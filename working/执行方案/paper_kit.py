def build_all():
    """输出给前端的数据包。"""
    papers = []
    for p in PAPERS:
        chs = []
        for c in p['chapters']:
            words = int(round(p['total'] * c['pct'] / 100.0 / 100.0)) * 100
            chs.append(dict(n=c['n'], pct=c['pct'], words=words, ask=c['ask'],
                            out=c['out'], trap=c['trap']))
        papers.append(dict(id=p['id'], name=p['name'], en=p['en'], total=p['total'],
                           span=p['span'], head=p['head'], one=p['one'],
                           note=p['note'], chapters=chs))
    return dict(
        papers=papers,
        flow=FLOW,
        sent=SENT,
        dedup=DEDUP,
        dedupRed=DEDUP_RED,
        aigc=AIGC,
        aigcLine=AIGC_LINE,
        format=FORMAT,
        ref=REF,
        refRule=REF_RULE,
        trans=TRANS,
        transRule=TRANS_RULE,
        charts=CHART_P,
        check=CHECK,
        pdef=PDEF,
        eval=EVAL,
        meta=dict(
            refStd='GB/T 7714—2015',
            heads=['论文类型', '建议周期', '字数区间'],
            note='排版参数取高校通行值；本校研究生院或学院模板优先于本表，冲突时以本校《学位论文撰写规范》为准。',
        ),
    )


