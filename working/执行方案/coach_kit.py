"""陪跑动作流（0 基础可执行版）

设计原则：
1. 一次只推 1 个动作。做完才解锁下一个，避免「一屏 8 万字」把人劝退。
2. 每个动作都要能在 15–30 分钟内做完，且有「做完的样子」可验收。
3. 每个动作都写清「为什么现在做这个」，让人知道不做会怎样。
4. 卡住时必须能自助：给 1–2 条最常见卡点的具体处置（去哪问、说什么话）。
5. 动作可指派到人，团队协同靠「谁手上有什么、交给谁」体现。

阶段顺序按真实比赛节奏：开局 → 选题 → 组队 → 开工 → 做主体 → 成稿 → 答辩 → 提交。
"""

