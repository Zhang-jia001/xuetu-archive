def build_all():
    acts = []
    for i, a in enumerate(ACTS):
        acts.append(dict(
            id=a['id'], ph=a['ph'], who=a['who'], min=a['min'],
            t=a['t'], why=a['why'], how=list(a['how']), done=a['done'],
            help=[list(h) for h in a.get('help', [])], link=a.get('link', ''),
            seq=i + 1,
        ))
    phs = []
    for p in PHASES:
        ids = [a['id'] for a in ACTS if a['ph'] == p['id']]
        phs.append(dict(id=p['id'], name=p['name'], days=p['days'],
                        goal=p['goal'], count=len(ids),
                        first=ids[0] if ids else '', last=ids[-1] if ids else ''))
    return dict(phases=phs, acts=acts, words=WORDS, who=WHO,
                total=len(acts),
                totalMin=sum(a['min'] for a in ACTS))


if __name__ == '__main__':
    d = build_all()
    print('动作 %d 个 · 阶段 %d 个 · 术语 %d 条 · 预计总耗时 %.1f 小时'
          % (d['total'], len(d['phases']), len(d['words']), d['totalMin'] / 60.0))
    for p in d['phases']:
        print('  %-8s %-22s %-14s %d 个动作 %s→%s'
              % (p['id'], p['name'], p['days'], p['count'], p['first'], p['last']))
    ids = [a['id'] for a in d['acts']]
    assert len(set(ids)) == len(ids), '动作 id 有重复'
    for a in d['acts']:
        assert a['how'] and a['done'] and a['why'], a['id'] + ' 缺字段'
    base_ids = set(ids)
    for evc, ev in EV.items():
        assert ev['label'] and ev['note'], evc + ' 缺 label/note'
        for aid, ov in ev['acts'].items():
            assert aid in base_ids, evc + '/' + aid + ' 不在通用动作里'
            assert ov.get('how') or ov.get('t'), evc + '/' + aid + ' 覆盖为空'
    print('  ✓ id 唯一、关键字段齐全、六赛事覆盖层校验通过（覆盖 %d 处）'
          % sum(len(v['acts']) for v in EV.values()))
