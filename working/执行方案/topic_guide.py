def event_key(ev):
    return {"正大杯": "zdb", "挑战杯": "dt", "挑战杯（小挑）": "xt",
            "大创": "dch", "国创赛": "gcs", "4C": "c4"}.get(ev)


def genre(ev, direction, cat):
    """赛事 + 方向 + 类别 → 辅导族"""
    d = direction or ""
    if ev == "正大杯":
        return "survey"
    if ev == "挑战杯（小挑）":
        return "xt"
    if ev == "国创赛":
        return "gcs"
    if ev == "大创":
        if d == "政策社会调查":
            return "dch_research"
        return "dch_research" if cat == "计算机" else "dch_startup"
    if ev == "挑战杯":
        return "dt_social" if cat == "商科" else "dt_tech"
    if ev == "4C":
        return {"微课与AI辅助教学": "c4_micro", "大数据应用": "c4_bigdata",
                "人工智能应用": "c4_ai", "物联网应用与物联网创新转化": "c4_iot",
                "软件应用与开发": "c4_soft"}.get(d, "c4_media")
    return None


def entry_for(ev, direction, cat):
    """每条选题的参赛入口（一句话）"""
    d = direction or ""
    if ev == "正大杯":
        return "正大杯·实践赛（先过个人知识赛）｜按市场调查口径做设计"
    if ev == "挑战杯（小挑）":
        g = XT_GROUP.get(d.split("·")[-1], "按方向对号入座")
        return f"小挑·{g}组｜校赛网评 → 省赛路演 → 国赛面试"
    if ev == "国创赛":
        if cat == "计算机":
            return "国创赛·高教主赛道（本科创意组／「人工智能+」类）；涉农可转红旅"
        return "国创赛·高教主赛道（新文科／创意组）；涉农或公益可转红旅赛道"
    if ev == "大创":
        if cat == "计算机" or d == "政策社会调查":
            return "大创 A 类创新训练｜结题须挂论文／专利／竞赛奖之一"
        return "大创 B 类创业训练（有真实经营可冲 C 类创业实践）"
    if ev == "挑战杯":
        if cat == "商科":
            return "挑战杯（大挑）·哲学社会科学类社会调查报告（5 组别对号入座）"
        return "挑战杯（大挑）·科技发明制作（按投入与含量选 A 类或 B 类）"
    if ev == "4C":
        if d in C4_LIMITED:
            return f"4C·{d}｜主题限定「中国古代建筑成就」（1911 年前）"
        return f"4C·{d}｜本届无主题限定"
    return ""


